def language(code: str | None) -> Language:
    try:
        return LANGUAGES[code]
    except (KeyError, TypeError):
        return LANGUAGES["en"]


def text(code: str | None, key: str) -> str:
    return UI.get(language(code).code, {}).get(key) or UI["en"][key]
